// Builds the single SQL file to run against the Railway MySQL when the MPP-15 epic merges to master.
//
// Source of truth: the table in .claude/contract/MPP-15-epic-breakdown/railway-migrations.md.
// Every row is concatenated, in table order, into mpp15-railway-golive.sql next to this script.
//
//   node foodbytes-app/database/build-golive.mjs          regenerate the go-live file
//   node foodbytes-app/database/build-golive.mjs --check  exit 1 if the file is stale or a
//                                                          ticket migration is missing from the tracker
//
// Run it (from the repo root or anywhere) every time a row is added to railway-migrations.md.
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const DB_DIR = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(DB_DIR, '..', '..');
const TRACKER = join(REPO, '.claude', 'contract', 'MPP-15-epic-breakdown', 'railway-migrations.md');
const OUT = join(DB_DIR, 'mpp15-railway-golive.sql');
const MIGRATIONS = join(DB_DIR, 'migrations');
// Ticket migrations written on/after this date belong to the epic and must be in the tracker.
const EPIC_START = '2026-10-13';

function trackerRows() {
  const rows = [];
  for (const line of readFileSync(TRACKER, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\|\s*(\d+)\s*\|\s*(MPP-\d+)\s*\|\s*(\S+\.sql)\s*\|/);
    if (m) rows.push({ order: Number(m[1]), ticket: m[2], path: m[3] });
  }
  if (rows.length === 0) throw new Error(`No migration rows found in ${TRACKER}`);
  rows.forEach((r, i) => {
    if (r.order !== i + 1) throw new Error(`Tracker order is not 1..n at row ${i + 1} (${r.path})`);
  });
  return rows;
}

function build(rows) {
  const parts = [
    '-- MPP-15 go-live: every Railway migration for the Pip\'s room epic, in apply order.',
    '-- GENERATED by foodbytes-app/database/build-golive.mjs from',
    '-- .claude/contract/MPP-15-epic-breakdown/railway-migrations.md. Do not edit by hand.',
    '--',
    '-- Run ONCE against the Railway `railway` schema BEFORE the merged backend deploys',
    '-- (Hibernate ddl-auto: validate refuses to start otherwise). Every section is idempotent,',
    '-- so after a partial failure fix the cause and re-run the whole file.',
    '--',
    ...rows.map((r) => `--   ${r.order}. ${r.ticket}  ${r.path.split('/').pop()}`),
    '',
  ];
  for (const r of rows) {
    const file = join(REPO, r.path);
    if (!existsSync(file)) throw new Error(`Tracker row ${r.order} points at a missing file: ${r.path}`);
    const sql = readFileSync(file, 'utf8').replace(/\r\n/g, '\n').trimEnd();
    parts.push(
      '',
      `-- ${'='.repeat(94)}`,
      `-- ${r.order}. ${r.ticket} — ${r.path}`,
      `-- ${'='.repeat(94)}`,
      '',
      sql,
    );
  }
  parts.push('', `SELECT 'MPP-15 go-live: ${rows.length} migrations applied' AS result;`, '');
  return parts.join('\n');
}

function untracked(rows) {
  const listed = new Set(rows.map((r) => r.path.split('/').pop()));
  return readdirSync(MIGRATIONS).filter(
    (f) => /-mpp\d+-.*\.sql$/i.test(f) && f.slice(0, 10) >= EPIC_START && !listed.has(f),
  );
}

const rows = trackerRows();
const sql = build(rows);
const missing = untracked(rows);
if (missing.length) {
  console.error(`Ticket migrations not in railway-migrations.md:\n  ${missing.join('\n  ')}`);
}

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  const stale = current !== sql;
  if (stale) console.error('mpp15-railway-golive.sql is stale - run: node foodbytes-app/database/build-golive.mjs');
  if (stale || missing.length) process.exit(1);
  console.log(`Go-live OK: ${rows.length} migrations`);
} else {
  writeFileSync(OUT, sql);
  console.log(`Wrote ${OUT} (${rows.length} migrations)`);
  if (missing.length) process.exit(1);
}
